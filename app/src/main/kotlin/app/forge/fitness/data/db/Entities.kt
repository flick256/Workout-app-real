/** A tick on a custom habit for one day (v7). Unticking deletes the row. */
@Serializable
@Entity(
    tableName = "habit_check",
    primaryKeys = ["habitId", "epochDay"],
    indices = [Index("epochDay")],
)
data class HabitCheckEntity(
    val habitId: String,
    val epochDay: Long,
    val checkedAt: Long,
)

